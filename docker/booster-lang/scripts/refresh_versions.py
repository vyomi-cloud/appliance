#!/usr/bin/env python3
"""Resolve the latest STABLE toolchain versions + sha256 checksums from the
official upstream sources and rewrite ../versions.json.

Fails loudly (non-zero exit, nothing written) if any version/checksum cannot be
resolved.  Usage:  python3 refresh_versions.py [--check]   (--check: diff only)
"""
import hashlib, json, re, sys, urllib.request, urllib.parse
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "versions.json"
ARCHES = {"amd64": {"go": "amd64", "node": "x64", "jdk": "x64", "rust": "x86_64", "dotnet": "x64"},
          "arm64": {"go": "arm64", "node": "arm64", "jdk": "aarch64", "rust": "aarch64", "dotnet": "arm64"}}


def get(url, as_json=False):
    req = urllib.request.Request(url, headers={"User-Agent": "vyomi-booster-refresh", "Accept": "*/*"})
    try:
        with urllib.request.urlopen(req, timeout=60) as r:
            data = r.read()
    except Exception as e:
        sys.exit(f"FATAL: cannot fetch {url}: {e}")
    return json.loads(data) if as_json else data.decode()


def need(v, what):
    if not v:
        sys.exit(f"FATAL: could not resolve {what}")
    return v


def hub_tags(repo, name):
    out, url = [], f"https://hub.docker.com/v2/repositories/library/{repo}/tags?page_size=100&name={name}"
    for _ in range(5):
        d = get(url, True)
        out += [t["name"] for t in d["results"]]
        url = d.get("next")
        if not url:
            break
    return out


def vkey(v):
    return tuple(int(x) for x in v.split("."))


def latest_hub(repo, suffix, pat):
    rx = re.compile(r"^(%s)-%s$" % (pat, re.escape(suffix)))
    c = [m.group(1) for t in hub_tags(repo, suffix) if (m := rx.match(t))]
    return need(max(c, key=vkey) if c else None, f"{repo} tag *-{suffix}")


def main():
    v = {"_comment": "Generated by scripts/refresh_versions.py - do not hand-edit. Base OS: debian trixie."}
    v["base_image"] = "debian:trixie-slim"
    # Go
    gos = get("https://go.dev/dl/?mode=json&include=all", True)
    g = need(next((x for x in gos if x["stable"]), None), "go")
    gov = g["version"][2:]
    sha = {f["arch"]: f["sha256"] for f in g["files"] if f["os"] == "linux" and f["kind"] == "archive"}
    v["go"] = {"version": gov, "sha256": {a: need(sha.get(m["go"]), f"go sha {a}") for a, m in ARCHES.items()}}
    # Node: newest LTS (+ npm bundled)
    idx = get("https://nodejs.org/dist/index.json", True)
    lts = need(next((x for x in idx if x["lts"]), None), "node lts")
    nv = lts["version"]
    sums = get(f"https://nodejs.org/dist/{nv}/SHASUMS256.txt")
    nsha = {}
    for a, m in ARCHES.items():
        mm = re.search(r"^(\w{64})  node-%s-linux-%s\.tar\.xz$" % (nv, m["node"]), sums, re.M)
        nsha[a] = need(mm and mm.group(1), f"node sha {a}")
    cur = [x for x in idx if not x["lts"] and re.fullmatch(r"v\d+\.\d+\.\d+", x["version"])]
    v["node"] = {"version": nv[1:], "npm": lts["npm"], "sha256": nsha,
                 "note": "LTS line. 'Current' is only listed when newer than LTS and stable: " +
                         (cur[0]["version"] if cur else "none right now (v27 is alpha)")}
    # Temurin LTS + latest feature release
    rel = get("https://api.adoptium.net/v3/info/available_releases", True)
    v["java"] = {}
    for label, major in (("lts", rel["most_recent_lts"]), ("latest", rel["most_recent_feature_release"])):
        assets = get(f"https://api.adoptium.net/v3/assets/latest/{major}/hotspot?image_type=jdk&os=linux&vendor=eclipse", True)
        ent = {"major": major, "sha256": {}, "url": {}}
        for a in assets:
            for arch, m in ARCHES.items():
                if a["binary"]["architecture"] == m["jdk"]:
                    ent["version"] = a["release_name"][4:]  # e.g. 25.0.5+8 / 27.0.1.0.2+1
                    ent["sha256"][arch] = a["binary"]["package"]["checksum"]
                    ent["url"][arch] = a["binary"]["package"]["link"]
        need(len(ent["sha256"]) == 2 and ent.get("version"), f"temurin {major}")
        v["java"][label] = ent
    # Rust (combined installer: rustc+cargo+std)
    t = get("https://static.rust-lang.org/dist/channel-rust-stable.toml")
    rv = need(re.search(r'\[pkg\.rust\]\nversion = "(\d+\.\d+\.\d+)', t), "rust").group(1)
    rsha, rurl = {}, {}
    for a, m in ARCHES.items():
        tri = f"{m['rust']}-unknown-linux-gnu"
        mm = re.search(r'\[pkg\.rust\.target\.%s\]\navailable = true\nurl = "[^"]+"\nhash = "[^"]+"\nxz_url = "([^"]+)"\nxz_hash = "(\w{64})"' % re.escape(tri), t)
        need(mm, f"rust {tri}")
        rurl[a], rsha[a] = mm.group(1), mm.group(2)
    cv = rv  # `cargo --version` tracks the toolchain release (manifest pkg version is the crate semver)
    v["rust"] = {"version": rv, "cargo": cv, "url": rurl, "sha256": rsha}
    # .NET: newest LTS/STS channel that is GA (not preview/rc)
    di = get("https://dotnetcli.blob.core.windows.net/dotnet/release-metadata/releases-index.json", True)["releases-index"]
    ch = need(next((c for c in di if re.fullmatch(r"\d+\.\d+\.\d+", c["latest-sdk"]) and c["support-phase"] in ("active", "maintenance")), None), "dotnet")
    rj = get(ch["releases.json"], True)
    sdk, dsha, durl = rj["latest-sdk"], {}, {}
    for f in rj["releases"][0]["sdk"]["files"]:
        for a, m in ARCHES.items():
            if f["rid"] == f"linux-{m['dotnet']}" and f["name"].endswith(".tar.gz"):
                durl[a], dsha[a] = f["url"], f["hash"]  # sha512
    need(len(durl) == 2, "dotnet files")
    v["dotnet"] = {"version": sdk, "runtime": rj["latest-runtime"], "channel": ch["channel-version"], "url": durl, "sha512": dsha}
    # Python / Ruby / PHP: official docker-library images (same Debian) copied into /usr/local
    v["python"] = {"version": latest_hub("python", "slim-trixie", r"3\.\d+\.\d+"), "image_tag_suffix": "slim-trixie"}
    v["ruby"] = {"version": latest_hub("ruby", "slim-trixie", r"\d+\.\d+\.\d+"), "image_tag_suffix": "slim-trixie"}
    v["php"] = {"version": latest_hub("php", "cli-trixie", r"\d+\.\d+\.\d+"), "image_tag_suffix": "cli-trixie"}
    # C/C++ come from Debian trixie apt (kept in sync with the base release)
    v["cpp"] = {"gcc_major": 14, "clang_major": 19, "note": "Debian trixie apt; smoke asserts major"}
    # package managers
    pip = get("https://pypi.org/pypi/pip/json", True)["info"]["version"]
    pnpm = get("https://registry.npmjs.org/pnpm/latest", True)["version"]
    yarn = get("https://registry.npmjs.org/yarn/latest", True)["version"]
    gr = get("https://services.gradle.org/versions/current", True)["version"]
    grs = get(f"https://downloads.gradle.org/distributions/gradle-{gr}-bin.zip.sha256").split()[0]
    mx = get("https://repo1.maven.org/maven2/org/apache/maven/apache-maven/maven-metadata.xml")
    mv = need(max((m for m in re.findall(r"<version>(\d+\.\d+\.\d+)</version>", mx)), key=vkey), "maven")
    mvs = get(f"https://repo1.maven.org/maven2/org/apache/maven/apache-maven/{mv}/apache-maven-{mv}-bin.tar.gz.sha512").split()[0]
    comp = get("https://getcomposer.org/versions", True)["stable"][0]["version"]
    # composer publishes no checksum file for versioned phars; pin by hashing at refresh time (TOFU, then immutable)
    comps = hashlib.sha256(urllib.request.urlopen(f"https://getcomposer.org/download/{comp}/composer.phar", timeout=60).read()).hexdigest()
    v["package_managers"] = {
        "pip": pip, "npm": lts["npm"], "pnpm": pnpm, "yarn_classic": yarn,
        "maven": {"version": mv, "sha512": mvs}, "gradle": {"version": gr, "sha256": grs},
        "cargo": cv, "go_mod": gov, "nuget": "bundled with dotnet sdk " + sdk,
        "gem": "bundled with ruby", "bundler": "bundled with ruby",
        "composer": {"version": comp, "sha256": comps}, "apt": "debian trixie"}
    new = json.dumps(v, indent=2) + "\n"
    if "--check" in sys.argv:
        print("up to date" if OUT.exists() and OUT.read_text() == new else "DIFFERS from resolved versions")
        return
    OUT.write_text(new)
    print("wrote", OUT)


main()
