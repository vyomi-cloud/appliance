/* Network Manager: global network -> site -> device -> link -> association -> transit gateway registration; VPC Integrations tab reflects it.
 *   BASE=http://127.0.0.1:9084 node consoles/tests/smoke-aws-networkmanager.mjs */
import { createRequire } from "node:module";
const require = createRequire(import.meta.url);
let pw;
try { pw = require(process.env.PW || "playwright"); } catch { pw = require("/Users/sudhirganti/Applications/simulator/portal/node_modules/playwright"); }
const BASE = process.env.BASE || "http://127.0.0.1:9084";
const UI = `${BASE}${process.env.UI_PATH || "/v4/aws/"}`;
const WIRE = `${BASE}${process.env.WIRE_PATH || "/_wire"}`;
const results = [];
const check = (name, ok, d = "") => { results.push({ name, ok }); console.log(`${ok ? "PASS" : "FAIL"} ${name}${d ? " - " + String(d).slice(0, 160) : ""}`); };
const browser = await pw.chromium.launch();
const page = await browser.newPage({ viewport: { width: 1440, height: 1400 } });
const errors = []; page.on("pageerror", (e) => errors.push(e.message));
const sc = (svc) => `AWS4-HMAC-SHA256 Credential=X/20261030/us-east-1/${svc}/aws4_request, SignedHeaders=host, Signature=0`;
await page.goto(UI + "#/networkmanager");
const ec2 = (params) => page.evaluate(async ([u, a, b]) => { const r = await fetch(`${u}/`, { method: "POST", headers: { authorization: a, "content-type": "application/x-www-form-urlencoded" }, body: b }); return r.text(); }, [WIRE, sc("ec2"), new URLSearchParams({ Version: "2016-11-15", ...params }).toString()]);
const tgx = await ec2({ Action: "CreateTransitGateway", Description: "smoke-tgw" });
const TGW = tgx.match(/<transitGatewayId>(tgw-[0-9a-f]+)/)?.[1];
check("transit gateway created in EC2 model", !!TGW, tgx.slice(0, 100));
const text = () => page.locator("body").innerText();
const dialog = () => page.getByRole("dialog");
await page.getByRole("button", { name: "Create global network" }).first().waitFor();
check("global networks is a real page", !/Not simulated in Vyomi/i.test(await text()));
await page.getByRole("button", { name: "Create global network" }).first().click();
await dialog().getByRole("textbox", { name: "Name" }).fill("smoke-wan");
await dialog().getByRole("button", { name: "Create global network" }).click();
await page.getByText(/global-network-/).first().waitFor({ timeout: 10000 });
check("global network created", true);
await page.getByRole("link", { name: /global-network-/ }).first().click();
await page.getByRole("tab", { name: "Sites" }).waitFor();
await page.getByRole("button", { name: "Create site" }).first().click();
await dialog().getByRole("textbox", { name: "Name" }).fill("hq");
await dialog().getByRole("button", { name: "Create site" }).click();
await page.getByText(/site-[0-9a-f]+/).first().waitFor({ timeout: 10000 });
check("site created", true);
await page.getByRole("tab", { name: "Devices" }).click();
await page.getByRole("button", { name: "Create device" }).first().click();
await dialog().getByRole("textbox", { name: "Name" }).fill("edge1");
await dialog().getByRole("button", { name: "Create device" }).click();
await page.getByText(/device-[0-9a-f]+/).first().waitFor({ timeout: 10000 });
check("device created", true);
await page.getByRole("tab", { name: "Transit gateways" }).click();
await page.getByRole("button", { name: "Register transit gateway" }).first().click();
await dialog().getByRole("button", { name: "Register", exact: true }).click();
await dialog().getByText(/Transit gateway.*(required|must)|TransitGatewayArn|invalid|ARN/i).first().waitFor({ timeout: 10000 });
check("registering with no gateway chosen surfaces the core's error", true);
await dialog().getByRole("button", { name: /Transit gateway/ }).click();
await page.getByRole("option", { name: new RegExp(TGW) }).click();
await dialog().getByRole("button", { name: "Register", exact: true }).click();
await page.getByText(new RegExp("transit-gateway/" + TGW)).first().waitFor({ timeout: 10000 });
check("transit gateway registered", true);
check("no page errors", errors.length === 0, errors.join(" | "));
await browser.close();
const bad = results.filter((r) => !r.ok);
console.log(`\n${results.length - bad.length}/${results.length} passed`);
process.exit(bad.length ? 1 : 0);
