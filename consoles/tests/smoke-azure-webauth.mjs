/* Function App Authentication (Entra authsettingsV2 + live enforcement) and the Azure OpenAI connection panel.
 *   BASE=http://127.0.0.1:9103 node consoles/tests/smoke-azure-webauth.mjs
 */
import { createRequire } from "node:module";
const require = createRequire(import.meta.url);
let pw; try { pw = require(process.env.PW || "playwright"); } catch { pw = require("/Users/sudhirganti/Applications/simulator/portal/node_modules/playwright"); }
const BASE = process.env.BASE || "http://127.0.0.1:9103";
const UI = `${BASE}${process.env.UI_PATH || "/v4/azure/"}`;
const WIRE = `${BASE}${process.env.WIRE_PATH || "/_wire"}`;
const results = [];
const check = (name, ok, d = "") => { results.push(ok); console.log(`${ok ? "PASS" : "FAIL"} ${name}${d ? " - " + String(d).slice(0, 160) : ""}`); };
const browser = await pw.chromium.launch();
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const errs = []; page.on("pageerror", (e) => errs.push(String(e)));
await page.goto(UI);
await page.waitForTimeout(1500);
const S = "00000000-0000-0000-0000-cloudlearn01";
const put = (p, b) => page.evaluate(async ([u, p, b]) => { const r = await fetch(u + p, { method: "PUT", headers: { "content-type": "application/json" }, body: JSON.stringify(b) }); return r.status; }, [WIRE, p, b]);
const RG = `/subscriptions/${S}/resourceGroups/wa-rg`;
await put(`/subscriptions/${S}/resourcegroups/wa-rg?api-version=2021-04-01`, { location: "eastus" });
await put(`${RG}/providers/Microsoft.Web/serverfarms/p1?api-version=2023-12-01`, { location: "eastus", sku: { name: "B1" } });
const a = await put(`${RG}/providers/Microsoft.Web/sites/fa1?api-version=2023-12-01`, { location: "eastus", kind: "functionapp,linux", properties: { serverFarmId: `${RG}/providers/Microsoft.Web/serverfarms/p1` } });
const f = await put(`${RG}/providers/Microsoft.Web/sites/fa1/functions/echo?api-version=2023-12-01`, { properties: { files: { "__init__.py": "def main(req):\n    return {'ok': True}\n" } } });
await put(`${RG}/providers/Microsoft.CognitiveServices/accounts/aoai1?api-version=2024-10-01`, { location: "eastus", kind: "OpenAI", sku: { name: "S0" }, properties: { customSubDomainName: "wa-aoai" } });
await put(`${RG}/providers/Microsoft.CognitiveServices/accounts/aoai1/deployments/gpt4o?api-version=2024-10-01`, { sku: { name: "Standard", capacity: 1 }, properties: { model: { format: "OpenAI", name: "gpt-4o", version: "2024-08-06" } } });
check("seed function app + function", a < 300 && f < 300, `${a}/${f}`);
const TEN = "11111111-2222-3333-4444-555555555555", CID = "99999999-8888-7777-6666-555555555555";
await page.goto(`${UI}#/functionapp/wa-rg/fa1/authentication`);
await page.getByLabel("Application client ID").waitFor({ timeout: 20000 });
await page.getByLabel("App Service authentication").check();
await page.getByLabel("Application client ID").fill("not-a-guid");
await page.getByLabel("Tenant ID").fill(TEN);
await page.getByRole("button", { name: "Save", exact: true }).click();
await page.getByText(/not a valid application/).waitFor({ timeout: 10000 });
check("invalid client ID rejected by the backend", true);
await page.getByLabel("Application client ID").fill(CID);
await page.getByLabel("Unauthenticated requests").selectOption("Return401");
await page.getByLabel("Allowed token audiences").fill(CID);
await page.getByRole("button", { name: "Save", exact: true }).click();
await page.waitForTimeout(1200);
await page.getByRole("button", { name: "Send request" }).click();
await page.getByTestId("probe-result").waitFor({ timeout: 10000 });
check("anonymous request is rejected (401)", /Unauthorized/.test(await page.getByTestId("probe-result").innerText()), await page.getByTestId("probe-result").innerText());
const b = (o) => Buffer.from(JSON.stringify(o)).toString("base64url");
const jwt = `${b({ alg: "none" })}.${b({ aud: CID, tid: TEN, exp: Math.floor(Date.now() / 1000) + 600 })}.sig`;
await page.getByLabel("Probe Authorization header").fill("Bearer " + jwt);
await page.getByRole("button", { name: "Send request" }).click();
await page.getByText("Request reached the function.").waitFor({ timeout: 10000 });
check("request with a valid Entra JWT passes", true);
const bad = `${b({ alg: "none" })}.${b({ aud: "other", tid: TEN, exp: Math.floor(Date.now() / 1000) + 600 })}.sig`;
await page.getByLabel("Probe Authorization header").fill("Bearer " + bad);
await page.getByRole("button", { name: "Send request" }).click();
await page.getByTestId("probe-result").filter({ hasText: /audience/ }).waitFor({ timeout: 10000 });
check("wrong audience rejected", true);
await page.getByLabel("Unauthenticated requests").selectOption("RedirectToLoginPage");
await page.getByRole("button", { name: "Save", exact: true }).click();
await page.waitForTimeout(1000);
await page.getByLabel("Probe Authorization header").fill("");
await page.getByRole("button", { name: "Send request" }).click();
await page.getByTestId("probe-result").filter({ hasText: /Redirecting/ }).waitFor({ timeout: 10000 });
check("RedirectToLoginPage answers with a redirect to Entra", true);
await page.goto(`${UI}#/functionapp/wa-rg/fa1/azureopenai`);
await page.getByLabel("Azure OpenAI account").waitFor({ timeout: 20000 });
await page.waitForTimeout(800);
await page.getByLabel("Authentication type").selectOption("managedIdentity");
await page.getByRole("button", { name: "Connect" }).click();
await page.getByText(/needs a system- or user-assigned identity/).waitFor({ timeout: 10000 });
check("managed identity mode refused without an identity", true);
await page.getByLabel("Authentication type").selectOption("key");
await page.getByRole("button", { name: "Connect" }).click();
await page.getByTestId("aoai-current").waitFor({ timeout: 10000 });
const cur = await page.getByTestId("aoai-current").innerText();
check("connection saved and resolved", /wa-aoai\.openai\.azure\.com/.test(cur) && /gpt4o \(exists\)/.test(cur), cur.replace(/\s+/g, " "));
await page.goto(`${UI}#/appservices`);
await page.waitForTimeout(500);
check("no page errors", errs.length === 0, errs[0]);
await browser.close();
process.exit(results.every(Boolean) ? 0 : 1);
