/* Stream Analytics job blade: create via UI, add Blob input/output, test + save query, start, results, stop.
 *   BASE=http://127.0.0.1:9103 node consoles/tests/smoke-azure-streamanalytics.mjs
 */
import { createRequire } from "node:module";
const require = createRequire(import.meta.url);
let pw; try { pw = require(process.env.PW || "playwright"); } catch { pw = require("/Users/sudhirganti/Applications/simulator/portal/node_modules/playwright"); }
const BASE = process.env.BASE || "http://127.0.0.1:9103";
const UI = `${BASE}${process.env.UI_PATH || "/v4/azure/"}`;
const WIRE = `${BASE}${process.env.WIRE_PATH || "/_wire"}`;
const results = [];
const check = (name, ok, d = "") => { results.push(ok); console.log(`${ok ? "PASS" : "FAIL"} ${name}${d ? " - " + String(d).slice(0, 140) : ""}`); };
const browser = await pw.chromium.launch();
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const errs = []; page.on("pageerror", (e) => errs.push(String(e)));
await page.goto(UI);
await page.waitForTimeout(1500);
const S = "00000000-0000-0000-0000-cloudlearn01";
const call = (method, p, b, hdr = {}) => page.evaluate(async ([u, method, p, b, hdr]) => { const r = await fetch(u + p, { method, headers: { "content-type": "application/json", ...hdr }, body: b === undefined ? undefined : (typeof b === "string" ? b : JSON.stringify(b)) }); return r.status; }, [WIRE, method, p, b, hdr]);
await call("PUT", `/subscriptions/${S}/resourcegroups/sa-rg?api-version=2021-04-01`, { location: "eastus" });
const st = await call("PUT", `/subscriptions/${S}/resourceGroups/sa-rg/providers/Microsoft.Storage/storageAccounts/saacct?api-version=2023-05-01`, { location: "eastus", kind: "StorageV2", sku: { name: "Standard_LRS" } });
const bh = { "x-ms-version": "2021-12-02", "x-ms-date": new Date().toUTCString(), authorization: "SharedKey saacct:x" };
const c1 = await call("PUT", "/saacct/sain?restype=container", undefined, bh);
const c2 = await call("PUT", "/saacct/saout?restype=container", undefined, bh);
const rows = [{ device: "a", temp: 20 }, { device: "a", temp: 30 }, { device: "b", temp: 50 }];
const up = await call("PUT", "/saacct/sain/data/1.json", rows.map((r) => JSON.stringify(r)).join("\n"), { ...bh, "x-ms-blob-type": "BlockBlob", "content-type": "application/json" });
check("seed storage + blobs", st < 300 && c1 < 300 && c2 < 300 && up < 300, `${st}/${c1}/${c2}/${up}`);
await page.goto(`${UI}#/streamanalytics`);
await page.getByRole("button", { name: /Create/ }).first().click();
await page.getByLabel("Job name").fill("job-ui");
await page.getByLabel("Resource group").selectOption("sa-rg");
await page.getByLabel("New Stream Analytics job").getByRole("button", { name: "Create" }).click();
await page.getByRole("link", { name: "job-ui" }).waitFor({ timeout: 15000 });
check("job created from the UI and listed", true);
await page.goto(`${UI}#/streamanalytics/sa-rg/job-ui/inputs`);
const addChild = async (alias, account, container, path) => {
  await page.getByLabel("Alias").fill(alias);
  await page.getByLabel("Storage account").fill(account);
  await page.getByLabel("Container").fill(container);
  if (path) await page.getByLabel("Path pattern").fill(path);
  await page.getByRole("button", { name: "Save", exact: true }).click();
};
await page.getByLabel("Alias").waitFor({ timeout: 15000 });
await addChild("in1", "saacct", "sain", "data/");
await page.getByRole("cell", { name: "in1", exact: true }).waitFor({ timeout: 10000 });
await page.getByRole("button", { name: "Test", exact: true }).click();
await page.getByTestId("test-in1").filter({ hasText: "TestSucceeded" }).waitFor({ timeout: 10000 });
check("input saved and connectivity test succeeds", true);
await page.goto(`${UI}#/streamanalytics/sa-rg/job-ui/outputs`);
await page.getByLabel("Alias").waitFor({ timeout: 15000 });
await addChild("out1", "saacct", "saout");
await page.getByRole("cell", { name: "out1", exact: true }).waitFor({ timeout: 10000 });
check("output saved", true);
await page.goto(`${UI}#/streamanalytics/sa-rg/job-ui/query`);
const ed = page.getByLabel("Query editor");
await ed.waitFor({ timeout: 15000 });
await ed.fill("SELECT * INTO nope FROM in1");
await page.getByRole("button", { name: "Test query" }).click();
await page.getByTestId("query-test").filter({ hasText: "TestFailed" }).waitFor({ timeout: 10000 });
check("bad query reported by Test query", true);
await ed.fill("SELECT device, COUNT(*) AS n, AVG(temp) AS avgt INTO out1 FROM in1 WHERE temp < 40 GROUP BY device");
await page.getByRole("button", { name: "Test query" }).click();
await page.getByTestId("query-test").filter({ hasText: "TestSucceeded" }).waitFor({ timeout: 10000 });
await page.getByRole("button", { name: "Save query" }).click();
await page.waitForTimeout(800);
check("valid query tested and saved", true);
await page.goto(`${UI}#/streamanalytics/sa-rg/job-ui`);
await page.getByRole("button", { name: "Start" }).click();
await page.getByTestId("job-state").filter({ hasText: "Running" }).waitFor({ timeout: 15000 });
check("job Running; run summary shows events", /3 input event\(s\), 1 output event/.test(await page.getByTestId("run-summary").innerText()));
await page.goto(`${UI}#/streamanalytics/sa-rg/job-ui/results`);
await page.getByRole("table", { name: "Results" }).waitFor({ timeout: 15000 });
await page.waitForTimeout(800);
const t = await page.getByRole("table", { name: "Results" }).innerText();
check("results come from the output blob", /device/.test(t) && /\ba\b/.test(t) && /25/.test(t), t.replace(/\s+/g, " "));
await page.goto(`${UI}#/streamanalytics/sa-rg/job-ui`);
await page.getByRole("button", { name: "Stop" }).click();
await page.getByTestId("job-state").filter({ hasText: "Stopped" }).waitFor({ timeout: 15000 });
check("job stopped", true);
check("no page errors", errs.length === 0, errs[0]);
await browser.close();
process.exit(results.every(Boolean) ? 0 : 1);
