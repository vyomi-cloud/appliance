import { createRequire } from "node:module";
import { mkdirSync } from "node:fs";
const require = createRequire(import.meta.url);
let pw; try { pw = require(process.env.PW || "playwright"); } catch { pw = require("/Users/sudhirganti/Applications/simulator/portal-OLD/node_modules/playwright"); }
const BASE = process.env.BASE || "http://127.0.0.1:8746", SHOTS = process.env.SHOTS || "/tmp/bedrockui-a";
mkdirSync(SHOTS, { recursive: true });
const results = [], check = (n, ok, d = "") => { results.push(ok); console.log(`${ok ? "PASS" : "FAIL"} ${n}${d ? " - " + String(d).slice(0, 160) : ""}`); };
const browser = await pw.chromium.launch(), page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const errs = []; page.on("pageerror", (e) => errs.push(String(e)));
const shot = (n) => page.screenshot({ path: `${SHOTS}/${n}.png`, fullPage: true });
const go = async (h) => { await page.goto(`${BASE}/nano/v4/aws/#/bedrock${h}`); await page.waitForTimeout(500); };
const txt = () => page.locator("body").innerText();
await go("");
await page.getByRole("heading", { name: "Overview" }).first().waitFor({ timeout: 60000 });
let t = await txt();
check("nav: real order Discover/Labs/Test/Infer/Tune/Build/Assess/Configure", /Discover[\s\S]*Labs[\s\S]*Test[\s\S]*Infer[\s\S]*Tune[\s\S]*Build[\s\S]*Assess[\s\S]*Configure and learn/.test(t));
check("overview: spotlight + Labs/Test/Infer/Tune/Build/Assess", /Model spotlight/.test(t) && /Labs/.test(t) && /Assess/.test(t));
await shot("001-overview");
await go("/quickstart"); await page.getByText("Choose your use case").waitFor({ timeout: 20000 });
await page.getByText("Generate text").first().click(); await page.getByTestId("quickstart-code").waitFor();
check("quickstart: tiles + sample code", /converse/.test(await page.getByTestId("quickstart-code").innerText())); await shot("004-quickstart");
await go("/models"); await page.getByRole("heading", { name: /Model catalog/ }).first().waitFor({ timeout: 30000 }); await page.waitForTimeout(1500);
check("catalog: lists models", /Qwen|Nova|Llama|vyomi|Claude/i.test(await txt())); await shot("005-model-catalog");
await go("/api-keys"); await page.getByText("How it works").waitFor({ timeout: 20000 });
await page.getByRole("tab", { name: "Long-term API keys" }).click(); await page.getByText("No long-term API keys").waitFor({ timeout: 20000 });
await shot("006-api-keys-empty");
await page.getByRole("button", { name: "Generate long-term API keys" }).first().click();
await page.getByRole("button", { name: "Generate", exact: true }).click();
await page.getByTestId("api-key-secret").waitFor({ timeout: 20000 });
const sec = await page.getByTestId("api-key-secret").locator("input").inputValue();
check("api keys: long-term key issued through IAM", sec.length > 20, sec.slice(0, 6) + "...");
await page.getByRole("button", { name: "Close" }).last().click(); await page.waitForTimeout(800);
check("api keys: key listed (BedrockAPIKey-*, Active)", /BedrockAPIKey-/.test(await txt()) && /Active/.test(await txt())); await shot("006-api-keys-long");
await go("/quotas"); await page.getByText("Quotas by model").first().waitFor({ timeout: 20000 }); await page.waitForTimeout(1500);
check("quotas: table + filters", /Any provider/.test(await txt()) && /Inference type/.test(await txt())); await shot("007-quotas");
await go("/compare-models"); await page.getByText("MODEL CAPABILITIES").first().waitFor({ timeout: 30000 }); await shot("008-compare");
await go("/playground"); await page.getByText("Select a model to get started").waitFor({ timeout: 20000 }); await shot("009-playground-empty");
await go("/tokenizer"); await page.getByText("Token result").waitFor({ timeout: 20000 });
await page.getByRole("button", { name: "Select model" }).click();
await page.getByRole("dialog").getByRole("button", { name: /Choose a model/ }).click(); await page.getByRole("option").first().click();
await page.getByRole("button", { name: "Apply" }).click();
await page.getByRole("button", { name: "Insert sample text" }).click();
await page.getByRole("button", { name: "Count tokens" }).click();
await page.waitForFunction(() => { const e = document.querySelector('[data-testid="token-count"]'); return e && /\d/.test(e.innerText); }, null, { timeout: 20000 }).catch(() => {});
const n = await page.getByTestId("token-count").innerText();
check("tokenizer: CountTokens returns a number", /^\d+$/.test(n.trim()), n); await shot("010-tokenizer");
check("no page errors", errs.length === 0, errs[0]);
await browser.close();
const bad = results.filter((x) => !x).length; console.log(`${results.length - bad}/${results.length} passed`); process.exit(bad ? 1 : 0);
