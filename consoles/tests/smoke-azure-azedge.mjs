/* Front Door / CDN profiles and Network Manager (security admin configurations) consoles over native ARM.
 *   PW=... BASE=http://127.0.0.1:9082 node consoles/tests/smoke-azure-azedge.mjs   (fresh dev server) */
import { createRequire } from "node:module";
const require = createRequire(import.meta.url);
let pw;
try { pw = require(process.env.PW || "playwright"); } catch { pw = require("/Users/sudhirganti/Applications/simulator/portal/node_modules/playwright"); }
const BASE = process.env.BASE || "http://127.0.0.1:9082";
const UI = `${BASE}${process.env.UI_PATH || "/v4/azure/"}`;
const WIRE = `${BASE}${process.env.WIRE_PATH || "/_wire"}`;
const SUB = "00000000-0000-0000-0000-cloudlearn01";
const n = Date.now() % 100000;
const RG = `edge-rg${n}`, FD = `fd${n}`, NM = `nm${n}`;
let bad = 0;
const check = (name, ok, d = "") => { if (!ok) bad++; console.log(`${ok ? "PASS" : "FAIL"} ${name}${d ? " - " + String(d).slice(0, 160) : ""}`); };
const browser = await pw.chromium.launch();
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const errors = []; page.on("pageerror", (e) => errors.push(e.message));
await page.goto(UI, { waitUntil: process.env.NANO ? "domcontentloaded" : "networkidle" });
if (process.env.NANO) await page.waitForFunction(() => navigator.serviceWorker?.controller && window.__vyomiNanoReady, null, { timeout: 240000, polling: 500 });
const wire = (path, init = {}) => page.evaluate(async ([u, i]) => { const r = await fetch(u, i); return { status: r.status, text: await r.text() }; }, [WIRE + path, init]);
const arm = (method, path, body, av = "2024-02-01") => wire(`/subscriptions/${SUB}${path}${path.includes("?") ? "&" : "?"}api-version=${av}`, { method, headers: { "content-type": "application/json" }, body: body ? JSON.stringify(body) : undefined });
const json = (r) => { try { return JSON.parse(r.text); } catch { return {}; } };
await arm("PUT", `/resourceGroups/${RG}`, { location: "eastus" }, "2021-04-01");
const dlg = () => page.getByRole("dialog");
const fill = async (label, v) => dlg().getByLabel(label, { exact: true }).fill(v);
const add = (noun) => page.getByRole("button", { name: `Add ${noun}`, exact: true }).click();

// ── Front Door ──
await page.goto(UI + "#/frontdoor");
await page.getByRole("button", { name: /Create/ }).first().click();
await dlg().getByRole("combobox", { name: "Resource group" }).selectOption(RG);
await fill("Profile name", FD);
await dlg().getByRole("button", { name: "Create", exact: true }).click();
await page.getByRole("link", { name: FD }).click();
await page.getByText("Front Door ID").waitFor({ timeout: 15000 });
check("profile created via UI is a Front Door profile", json(await arm("GET", `/resourceGroups/${RG}/providers/Microsoft.Cdn/profiles/${FD}`)).kind === "frontdoor");
await page.getByRole("link", { name: "Endpoints and routes" }).click();
await add("endpoint"); await fill("Endpoint name", "ep1"); await dlg().getByRole("button", { name: "Add", exact: true }).click();
await page.getByRole("cell", { name: "ep1", exact: true }).waitFor({ timeout: 10000 });
check("endpoint has a derived azurefd.net host", /azurefd\.net$/.test(json(await arm("GET", `/resourceGroups/${RG}/providers/Microsoft.Cdn/profiles/${FD}/afdEndpoints/ep1`)).properties?.hostName || ""));
await page.getByRole("link", { name: "Origin groups" }).click();
await add("origin group"); await fill("Origin group name", "og1"); await dlg().getByRole("button", { name: "Add", exact: true }).click();
await page.getByRole("radio", { name: "Select og1" }).waitFor({ timeout: 10000 });
await page.getByRole("radio", { name: "Select og1" }).check();
await add("origin"); await fill("Origin name", "o1"); await fill("Host name", "origin.example.com"); await fill("Weight (1-1000)", "5000");
await dlg().getByRole("button", { name: "Add", exact: true }).click();
await dlg().getByText(/weight/i).first().waitFor({ timeout: 8000 });
check("origin weight out of range is rejected with Azure's error", (json(await arm("GET", `/resourceGroups/${RG}/providers/Microsoft.Cdn/profiles/${FD}/originGroups/og1/origins/o1`)).error?.code) === "ResourceNotFound");
await fill("Weight (1-1000)", "500");
await dlg().getByRole("button", { name: "Add", exact: true }).click();
await page.getByRole("cell", { name: "origin.example.com" }).waitFor({ timeout: 10000 });
check("origin created", json(await arm("GET", `/resourceGroups/${RG}/providers/Microsoft.Cdn/profiles/${FD}/originGroups/og1/origins/o1`)).properties?.weight === 500);
await page.getByRole("link", { name: "Endpoints and routes" }).click();
await page.getByRole("radio", { name: "Select ep1" }).check();
await add("route"); await fill("Route name", "r1"); await fill("Origin group name", "ghost"); await dlg().getByRole("button", { name: "Add", exact: true }).click();
await dlg().getByText(/does not exist|OriginGroupNotFound/i).first().waitFor({ timeout: 8000 });
check("route to a missing origin group is rejected", true);
await fill("Origin group name", "og1"); await dlg().getByRole("button", { name: "Add", exact: true }).click();
await page.getByRole("cell", { name: "r1", exact: true }).waitFor({ timeout: 10000 });
check("route created against og1", !!json(await arm("GET", `/resourceGroups/${RG}/providers/Microsoft.Cdn/profiles/${FD}/afdEndpoints/ep1/routes/r1`)).properties?.originGroup?.id);

// ── Network Manager ──
await page.goto(UI + "#/networkmanagers");
await page.getByRole("button", { name: /Create/ }).first().click();
await dlg().getByRole("combobox", { name: "Resource group" }).selectOption(RG);
await fill("Network manager name", NM);
await dlg().getByRole("button", { name: "Create", exact: true }).click();
await page.getByRole("link", { name: NM }).click();
await page.getByText("Control plane only").waitFor({ timeout: 15000 });
await page.getByRole("link", { name: "Network groups" }).click();
await add("network group"); await fill("Group name", "g1"); await dlg().getByRole("button", { name: "Add", exact: true }).click();
await page.getByRole("radio", { name: "Select g1" }).waitFor({ timeout: 10000 });
await page.getByRole("link", { name: "Security admin configurations" }).click();
await add("security admin configuration"); await fill("Configuration name", "sec1"); await dlg().getByRole("button", { name: "Add", exact: true }).click();
await page.getByRole("radio", { name: "Select sec1" }).waitFor({ timeout: 10000 });
await page.getByRole("radio", { name: "Select sec1" }).check();
await add("rule collection"); await fill("Collection name", "rc1"); await fill("Applies to network group", "g1"); await dlg().getByRole("button", { name: "Add", exact: true }).click();
await page.getByRole("radio", { name: "Select rc1" }).waitFor({ timeout: 10000 });
await page.getByRole("radio", { name: "Select rc1" }).check();
await add("admin rule"); await fill("Rule name", "deny-ssh"); await fill("Priority (1-4096)", "5000"); await dlg().getByRole("button", { name: "Add", exact: true }).click();
await dlg().getByText(/priority/i).first().waitFor({ timeout: 8000 });
check("admin rule priority 5000 rejected (1-4096)", true);
await fill("Priority (1-4096)", "100"); await dlg().getByRole("button", { name: "Add", exact: true }).click();
await page.getByRole("cell", { name: "deny-ssh", exact: true }).waitFor({ timeout: 10000 });
const NMP = `/resourceGroups/${RG}/providers/Microsoft.Network/networkManagers/${NM}`;
const rule = json(await arm("GET", `${NMP}/securityAdminConfigurations/sec1/ruleCollections/rc1/rules/deny-ssh`, null, "2023-09-01"));
check("security admin rule stored with Deny/Inbound/22", rule.properties?.access === "Deny" && rule.properties?.direction === "Inbound" && rule.properties?.destinationPortRanges?.[0] === "22", JSON.stringify(rule.properties).slice(0, 120));
check("no page errors", errors.length === 0, errors.join("|"));
await browser.close();
process.exit(bad ? 1 : 0);
