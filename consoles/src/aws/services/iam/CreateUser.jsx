/* Create user — 3-step wizard. Console access (login profile), permissions (add to
 * group / attach policies directly), tags are all applied via real calls after CreateUser. */
import { useState } from "react";
import Wizard from "@cloudscape-design/components/wizard";
import Container from "@cloudscape-design/components/container";
import Header from "@cloudscape-design/components/header";
import FormField from "@cloudscape-design/components/form-field";
import Input from "@cloudscape-design/components/input";
import Checkbox from "@cloudscape-design/components/checkbox";
import RadioGroup from "@cloudscape-design/components/radio-group";
import ExpandableSection from "@cloudscape-design/components/expandable-section";
import Table from "@cloudscape-design/components/table";
import SpaceBetween from "@cloudscape-design/components/space-between";
import Box from "@cloudscape-design/components/box";
import TagEditor from "@cloudscape-design/components/tag-editor";
import Select from "@cloudscape-design/components/select";
import { useAsync } from "../../../common/useAsync.js";
import { useNotify } from "../../../common/notify.jsx";
import { navigate } from "../../../common/router.js";
import { ErrorAlert } from "../../kit/common.jsx";
import * as api from "./api.js";

function DetailsStep({ s, set }) {
  return (
    <SpaceBetween size="l">
      <Container header={<Header variant="h2">User details</Header>}>
        <FormField label="User name" constraintText="Up to 64 characters. Valid characters: A-Z, a-z, 0-9, and + = , . @ _ - (hyphen)">
          <Input value={s.userName} onChange={({ detail }) => set({ userName: detail.value })} ariaLabel="User name" />
        </FormField>
      </Container>
      <Container header={<Header variant="h2">Provide user access to the AWS Management Console - optional</Header>}>
        <SpaceBetween size="m">
          <Checkbox checked={s.consoleAccess} onChange={({ detail }) => set({ consoleAccess: detail.checked })}>Provide user access to the AWS Management Console - optional</Checkbox>
          {s.consoleAccess && (
            <SpaceBetween size="m">
              <FormField label="Are you providing console access to a person?">
                <RadioGroup value={s.personAccess} onChange={({ detail }) => set({ personAccess: detail.value })}
                  items={[{ value: "identity-center", label: "Specify a user in Identity Center - Recommended" }, { value: "iam-user", label: "I want to create an IAM user" }]} />
              </FormField>
              {s.personAccess === "iam-user" && (
                <>
                  <FormField label="Console password">
                    <RadioGroup value={s.pwType} onChange={({ detail }) => set({ pwType: detail.value })}
                      items={[{ value: "auto", label: "Autogenerated password" }, { value: "custom", label: "Custom password" }]} />
                  </FormField>
                  {s.pwType === "custom" && <FormField label="Custom password"><Input type="password" value={s.customPw} onChange={({ detail }) => set({ customPw: detail.value })} ariaLabel="Custom password" /></FormField>}
                  <Checkbox checked={s.resetRequired} onChange={({ detail }) => set({ resetRequired: detail.checked })}>Users must create a new password at next sign-in - Recommended</Checkbox>
                </>
              )}
            </SpaceBetween>
          )}
        </SpaceBetween>
      </Container>
    </SpaceBetween>
  );
}

function PermissionsStep({ s, set, groups, policies, reloadGroups }) {
  const notify = useNotify();
  const [newGroup, setNewGroup] = useState("");
  return (
    <SpaceBetween size="l">
      <Container header={<Header variant="h2">Permissions options</Header>}>
        <RadioGroup value={s.permOption} onChange={({ detail }) => set({ permOption: detail.value, selectedGroups: [], selectedPolicies: [] })}
          items={[{ value: "group", label: "Add user to group" }, { value: "copy", label: "Copy permissions" }, { value: "attach", label: "Attach policies directly" }]} />
      </Container>
      {s.permOption === "group" && (
        <Container header={<Header variant="h2" actions={<SpaceBetween direction="horizontal" size="xs">
          <Input value={newGroup} onChange={({ detail }) => setNewGroup(detail.value)} placeholder="New group name" ariaLabel="New group name" />
          <button type="button" onClick={async () => { if (!newGroup) return; try { await api.createGroup({ GroupName: newGroup }); notify.success(`Group "${newGroup}" created.`); setNewGroup(""); reloadGroups(); } catch (e) { notify.error(e); } }}>Create group</button>
        </SpaceBetween>}>Get started with groups</Header>}>
          <Table variant="embedded" items={groups} trackBy="GroupName" selectionType="multi"
            selectedItems={groups.filter((g) => s.selectedGroups.includes(g.GroupName))}
            onSelectionChange={({ detail }) => set({ selectedGroups: detail.selectedItems.map((g) => g.GroupName) })}
            columnDefinitions={[{ id: "name", header: "Group name", cell: (g) => g.GroupName }, { id: "u", header: "Users", cell: () => "-" }, { id: "p", header: "Attached policies", cell: () => "-" }, { id: "c", header: "Created", cell: () => "-" }]}
            empty={<Box textAlign="center" color="inherit"><b>No groups</b></Box>} />
        </Container>
      )}
      {s.permOption === "attach" && (
        <Container header={<Header variant="h2">Permissions policies</Header>}>
          <Table variant="embedded" items={policies} trackBy="Arn" selectionType="multi"
            selectedItems={policies.filter((p) => s.selectedPolicies.includes(p.Arn))}
            onSelectionChange={({ detail }) => set({ selectedPolicies: detail.selectedItems.map((p) => p.Arn) })}
            columnDefinitions={[{ id: "name", header: "Policy name", cell: (p) => p.PolicyName }, { id: "t", header: "Type", cell: () => "Managed" }, { id: "e", header: "Attached entities", cell: (p) => p.AttachmentCount || 0 }]}
            empty={<Box textAlign="center" color="inherit"><b>No policies</b></Box>} />
        </Container>
      )}
      <ExpandableSection headerText="Set permissions boundary - optional">
        <Checkbox checked={s.useBoundary} onChange={({ detail }) => set({ useBoundary: detail.checked })}>Use a permissions boundary to control the maximum permissions</Checkbox>
        {s.useBoundary && (
          <FormField label="Policy">
            <Select selectedOption={s.boundaryArn ? { value: s.boundaryArn, label: policies.find((p) => p.Arn === s.boundaryArn)?.PolicyName } : null}
              onChange={({ detail }) => set({ boundaryArn: detail.selectedOption.value })}
              options={policies.map((p) => ({ value: p.Arn, label: p.PolicyName }))} placeholder="Choose a policy" />
          </FormField>
        )}
      </ExpandableSection>
    </SpaceBetween>
  );
}

function ReviewStep({ s, goto }) {
  return (
    <SpaceBetween size="l">
      <Container header={<Header variant="h2" actions={<a onClick={() => goto(0)} style={{ cursor: "pointer" }}>Edit</a>}>User details</Header>}>
        <SpaceBetween size="s">
          <div><Box variant="awsui-key-label">User name</Box><div>{s.userName}</div></div>
          <div><Box variant="awsui-key-label">Console password type</Box><div>{s.consoleAccess && s.personAccess === "iam-user" ? (s.pwType === "auto" ? "Autogenerated password" : "Custom password") : "None"}</div></div>
          <div><Box variant="awsui-key-label">Require password reset</Box><div>{s.consoleAccess && s.personAccess === "iam-user" && s.resetRequired ? "Yes" : "No"}</div></div>
        </SpaceBetween>
      </Container>
      <Container header={<Header variant="h2" actions={<a onClick={() => goto(1)} style={{ cursor: "pointer" }}>Edit</a>}>Permissions summary</Header>}>
        <Table variant="embedded"
          items={s.permOption === "group" ? s.selectedGroups.map((n) => ({ name: n, type: "Group", used: "Add user to group" })) : s.permOption === "attach" ? s.selectedPolicies.map((arn) => ({ name: arn, type: "Managed policy", used: "Attach policy" })) : []}
          columnDefinitions={[{ id: "n", header: "Name", cell: (r) => r.name }, { id: "t", header: "Type", cell: (r) => r.type }, { id: "u", header: "Used as", cell: (r) => r.used }]}
          empty={<Box textAlign="center" color="inherit"><b>No resources</b></Box>} />
      </Container>
      <Container header={<Header variant="h2" actions={<a onClick={() => goto(1)} style={{ cursor: "pointer" }}>Edit</a>}>Tags - optional</Header>}>
        {s.tags.length ? s.tags.map((t) => <div key={t.key}>{t.key} = {t.value}</div>) : <Box color="text-body-secondary">No tags</Box>}
      </Container>
    </SpaceBetween>
  );
}

export default function CreateUser() {
  const notify = useNotify();
  const [idx, setIdx] = useState(0);
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState(null);
  const data = useAsync(() => Promise.all([api.listGroups(), api.listPolicies()]), []);
  const [s, setS] = useState({
    userName: "", consoleAccess: false, personAccess: "identity-center", pwType: "auto", customPw: "", resetRequired: true,
    permOption: "group", selectedGroups: [], selectedPolicies: [], useBoundary: false, boundaryArn: "", tags: [],
  });
  const set = (patch) => setS((prev) => ({ ...prev, ...patch }));
  if (data.loading) return <Box padding="l">Loading…</Box>;
  const [groups, policies] = data.data;

  const finish = async () => {
    setBusy(true); setError(null);
    try {
      await api.createUser({ UserName: s.userName });
      if (s.consoleAccess && s.personAccess === "iam-user") {
        const pw = s.pwType === "auto" ? Math.random().toString(36).slice(2, 10) + "Aa1!" : s.customPw;
        await api.createLoginProfile(s.userName, pw, s.resetRequired);
      }
      if (s.permOption === "group") for (const g of s.selectedGroups) await api.addUserToGroup(g, s.userName);
      if (s.permOption === "attach") for (const arn of s.selectedPolicies) await api.attachUserPolicy(s.userName, arn);
      if (s.useBoundary && s.boundaryArn) await api.putUserPermissionsBoundary(s.userName, s.boundaryArn);
      const tags = s.tags.filter((t) => !t.markedForRemoval && t.key);
      if (tags.length) await api.tagUser(s.userName, tags);
      notify.success(`User "${s.userName}" created.`);
      navigate("iam", "users", s.userName);
    } catch (e) { setError(e); } finally { setBusy(false); }
  };

  const steps = [
    { title: "Specify user details", content: <DetailsStep s={s} set={set} /> },
    { title: "Set permissions", content: <PermissionsStep s={s} set={set} groups={groups} policies={policies} reloadGroups={data.reload} /> },
    { title: "Review and create", content: <>
      {error && <Box padding={{ bottom: "s" }}><ErrorAlert error={error} header="Couldn't create user" /></Box>}
      <ReviewStep s={s} goto={setIdx} />
      <Container header={<Header variant="h2">Tags - optional</Header>}>
        <FormField label="Tags" description="You can add up to 50 more tags."><TagEditor tags={s.tags} onChange={({ detail }) => set({ tags: detail.tags })} /></FormField>
      </Container>
    </> },
  ];

  return (
    <Box padding={{ top: "l" }}>
      <Wizard
        activeStepIndex={idx}
        onNavigate={({ detail }) => setIdx(detail.requestedStepIndex)}
        onCancel={() => navigate("iam", "users")}
        onSubmit={finish}
        isLoadingNextStep={busy}
        submitButtonText="Create user"
        i18nStrings={{ stepNumberLabel: (n) => `Step ${n}`, collapsedStepsLabel: (n, total) => `Step ${n} of ${total}`, cancelButton: "Cancel", previousButton: "Previous", nextButton: "Next", optional: "optional" }}
        steps={steps}
      />
    </Box>
  );
}
