/* Lambda "Build with Infrastructure Composer" (AWS-10): the shared visual canvas bound to real services.
 * Deploying creates a REAL CloudFormation stack for the supported resources (SQS/SNS/S3/DynamoDB), real Lambda functions
 * through CreateFunction, real event source mappings (SQS -> function) and real SNS subscriptions (SNS -> function),
 * then records the application. */
import { useMemo, useState } from "react";
import Box from "@cloudscape-design/components/box";
import Button from "@cloudscape-design/components/button";
import FormField from "@cloudscape-design/components/form-field";
import Input from "@cloudscape-design/components/input";
import Select from "@cloudscape-design/components/select";
import SpaceBetween from "@cloudscape-design/components/space-between";
import Textarea from "@cloudscape-design/components/textarea";
import Canvas from "../../kit/Canvas.jsx";
import { ErrorAlert } from "../../kit/common.jsx";
import { useNotify } from "../../../common/notify.jsx";
import { navigate } from "../../../common/router.js";
import { getRegion } from "../../../common/wire.js";
import * as api from "./api.js";
import * as cfn from "../cloudformation/api.js";
import * as sns from "../sns/api.js";

const ACCOUNT = "123456789012";
const RUNTIMES = ["python3.12", "python3.11", "python3.10"];

export const COMPOSER_PALETTE = [
  { type: "function", idPrefix: "function", label: "Lambda function", group: "Compute", color: "#b7791f", defaults: { runtime: "python3.12" } },
  { type: "queue", idPrefix: "queue", label: "SQS queue", group: "Event sources", color: "#8456ce", defaults: {} },
  { type: "topic", idPrefix: "topic", label: "SNS topic", group: "Event sources", color: "#d91515", defaults: {} },
  { type: "bucket", idPrefix: "bucket", label: "S3 bucket", group: "Resources", color: "#037f0c", defaults: {} },
  { type: "table", idPrefix: "table", label: "DynamoDB table", group: "Resources", color: "#0972d3", defaults: {} },
];
const CFN_TYPE = { queue: "AWS::SQS::Queue", topic: "AWS::SNS::Topic", bucket: "AWS::S3::Bucket", table: "AWS::DynamoDB::Table" };
const slug = (s) => String(s).toLowerCase().replace(/[^a-z0-9-]/g, "-").replace(/^-+|-+$/g, "");

/** graph -> { stack template (the deployable non-function resources), functions, wiring } */
export function composerPlan(app, graph) {
  const phys = (n) => `${slug(app)}-${slug(n.label)}`;
  const Resources = {};
  graph.nodes.filter((n) => CFN_TYPE[n.type]).forEach((n) => {
    const logical = n.id.replace(/[^A-Za-z0-9]/g, "");
    const name = phys(n);
    const props = n.type === "queue" ? { QueueName: name } : n.type === "topic" ? { TopicName: name } : n.type === "bucket" ? { BucketName: name }
      : { TableName: name, BillingMode: "PAY_PER_REQUEST", AttributeDefinitions: [{ AttributeName: "id", AttributeType: "S" }], KeySchema: [{ AttributeName: "id", KeyType: "HASH" }] };
    Resources[logical] = { Type: CFN_TYPE[n.type], Properties: props };
  });
  const template = { AWSTemplateFormatVersion: "2010-09-09", Description: `Generated by the Lambda Infrastructure Composer canvas for ${app}`, Resources };
  const functions = graph.nodes.filter((n) => n.type === "function").map((n) => ({ node: n, name: phys(n) }));
  const wiring = graph.edges.map((e) => ({ src: graph.nodes.find((n) => n.id === e.from), fn: graph.nodes.find((n) => n.id === e.to) })).filter((w) => w.src && w.fn);
  return { template, functions, wiring, phys };
}

export default function Composer() {
  const notify = useNotify();
  const [graph, setGraph] = useState({ nodes: [], edges: [] });
  const [selected, setSelected] = useState(null);
  const [name, setName] = useState("");
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState(null);
  const [steps, setSteps] = useState([]);
  const nameOk = /^[A-Za-z][-A-Za-z0-9]{0,40}$/.test(name);
  const plan = useMemo(() => composerPlan(name || "app", graph), [name, graph]);
  const labelsOk = new Set(graph.nodes.map((n) => slug(n.label))).size === graph.nodes.length && graph.nodes.every((n) => slug(n.label));

  const deploy = async () => {
    setBusy(true); setError(null); setSteps([]);
    const log = (s) => setSteps((x) => [...x, s]);
    try {
      const { template, functions, wiring, phys } = composerPlan(name, graph);
      const region = getRegion();
      if (Object.keys(template.Resources).length) {
        await cfn.createStack({ name: slug(name), templateBody: JSON.stringify(template), capabilities: [] });
        log(`Created CloudFormation stack ${slug(name)} (${Object.keys(template.Resources).length} resources)`);
      }
      const fnArn = {};
      for (const f of functions) {
        const rt = f.node.data?.runtime || "python3.12";
        const r = await api.createFunction({ FunctionName: f.name, Runtime: rt, Architectures: ["x86_64"], Role: `arn:aws:iam::${ACCOUNT}:role/service-role/lambda-basic-execution`, Code: { Source: api.defaultSource(rt) } });
        fnArn[f.node.id] = r.FunctionArn || `arn:aws:lambda:${region}:${ACCOUNT}:function:${f.name}`;
        log(`Created Lambda function ${f.name}`);
      }
      for (const w of wiring) {
        const fname = phys(w.fn);
        if (w.src.type === "queue") {
          await api.createEventSourceMapping({ FunctionName: fname, EventSourceArn: `arn:aws:sqs:${region}:${ACCOUNT}:${phys(w.src)}`, BatchSize: 10 });
          log(`Mapped SQS queue ${phys(w.src)} to ${fname}`);
        } else if (w.src.type === "topic") {
          await sns.subscribe(`arn:aws:sns:${region}:${ACCOUNT}:${phys(w.src)}`, "lambda", fnArn[w.fn.id]);
          log(`Subscribed ${fname} to SNS topic ${phys(w.src)}`);
        }
      }
      await api.createApplication({ Name: name, Description: "Built with the Infrastructure Composer canvas", Template: "Infrastructure Composer canvas" });
      notify.success(`Deployed application "${name}" from the canvas.`);
      navigate("lambda", "applications");
    } catch (e) { setError(e); } finally { setBusy(false); }
  };

  return (
    <SpaceBetween size="l">
      <Canvas ariaLabel="Application canvas" palette={COMPOSER_PALETTE} nodes={graph.nodes} edges={graph.edges} onChange={setGraph}
        selectedId={selected} onSelect={setSelected} height={380}
        emptyHint="Add a Lambda function and the event sources and resources it needs."
        canConnect={(a, b) => (b.type !== "function" || !["queue", "topic"].includes(a.type) ? "Wire an SQS queue or SNS topic to a Lambda function (event source)." : true)}
        renderInspector={(n, patch) => (
          <SpaceBetween size="s">
            <FormField label="Name" description="Letters, numbers and hyphens."><Input value={n.label} ariaLabel="Node name" onChange={({ detail }) => patch({ label: detail.value })} /></FormField>
            {n.type === "function" && <FormField label="Runtime"><Select selectedOption={{ value: n.data.runtime, label: n.data.runtime }} ariaLabel="Runtime"
              options={RUNTIMES.map((r) => ({ value: r, label: r }))} onChange={({ detail }) => patch({ data: { runtime: detail.selectedOption.value } })} /></FormField>}
            {n.type === "table" && <Box variant="small" color="text-body-secondary">On-demand billing, partition key "id" (String).</Box>}
          </SpaceBetween>
        )} />
      <FormField label="Application name" constraintText="Starts with a letter; letters, numbers and hyphens."
        errorText={!labelsOk && graph.nodes.length ? "Every node needs a unique name." : null}>
        <Input value={name} ariaLabel="Application name" onChange={({ detail }) => setName(detail.value)} />
      </FormField>
      <FormField label="Stack template for the resources on the canvas" description="Lambda functions, event source mappings and SNS subscriptions are created through their own service APIs; everything else is this CloudFormation template.">
        <Textarea readOnly rows={8} ariaLabel="Generated template" value={JSON.stringify(plan.template, null, 2)} />
      </FormField>
      {error && <ErrorAlert error={error} />}
      {steps.length > 0 && <Box variant="small" data-composer-steps="">{steps.map((s) => <div key={s}>{s}</div>)}</Box>}
      <Box float="right"><Button variant="primary" loading={busy} disabled={!nameOk || !graph.nodes.length || !labelsOk} onClick={deploy}>Deploy application</Button></Box>
    </SpaceBetween>
  );
}
