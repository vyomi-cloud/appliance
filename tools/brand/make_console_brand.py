#!/usr/bin/env python3
"""Generate the console top-bar wordmarks from the portal's official Vyomi logo.

Source: static/brand/vyomi-wordmark-light.png (transparent, dark lettering — the same file
the portal serves). Output: consoles/src/common/brand-assets.js with two inlined PNGs
(height 64 px for 2x displays):
  light  — original colours, for light top bars (GCP lens)
  dark   — lettering recoloured to white, orbit untouched, for dark bars (AWS, Azure)

    python3 tools/brand/make_console_brand.py      (needs Pillow)
"""
import base64
import io
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "static" / "brand" / "vyomi-wordmark-light.png"
OUT = ROOT / "consoles" / "src" / "common" / "brand-assets.js"
H = 64


def trimmed(im):
    return im.crop(im.getbbox())


def for_dark_bar(im):
    px = im.load()
    for y in range(im.height):
        for x in range(im.width):
            r, g, b, a = px[x, y]
            if a and max(r, g, b) < 110 and abs(r - b) < 60:   # dark, unsaturated = lettering
                px[x, y] = (255, 255, 255, a)
    return im


def b64(im):
    buf = io.BytesIO()
    im.save(buf, "PNG", optimize=True)
    return base64.b64encode(buf.getvalue()).decode()


src = trimmed(Image.open(SRC).convert("RGBA"))
w = round(src.width * H / src.height)
light = src.resize((w, H), Image.LANCZOS)
dark = for_dark_bar(light.copy())
OUT.write_text(
    "/* GENERATED by tools/brand/make_console_brand.py from static/brand/vyomi-wordmark-light.png\n"
    " * (the portal's official logo). Do not edit — re-run the script. */\n"
    f"export const WORDMARK_W = {w};\nexport const WORDMARK_H = {H};\n"
    f'export const WORDMARK_LIGHT = "data:image/png;base64,{b64(light)}";\n'
    f'export const WORDMARK_DARK = "data:image/png;base64,{b64(dark)}";\n')
print(f"wrote {OUT.relative_to(ROOT)} ({w}x{H}, {OUT.stat().st_size // 1024} KB)")
