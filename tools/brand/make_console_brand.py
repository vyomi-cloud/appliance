#!/usr/bin/env python3
"""Generate the console top-bar wordmarks from the official Vyomi text logo.

Source: static/brand/vyomi-text.png (black "vyomi" lettering on white). Every console's
Vyomi brand (top bars, menu headers — AWS, Google Cloud, Azure) is drawn from it.
Output: consoles/src/common/brand-assets.js with two inlined transparent PNGs (height 64 px
for 2x displays):
  light  — dark lettering, for light top bars (GCP lens)
  dark   — white lettering, for dark bars (AWS, Azure)

    python3 tools/brand/make_console_brand.py      (needs Pillow)
"""
import base64
import io
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "static" / "brand" / "vyomi-text.png"
OUT = ROOT / "consoles" / "src" / "common" / "brand-assets.js"
H = 64


def lettering(path, rgb):
    """White background → transparent: alpha follows how dark each pixel is (keeps the
    anti-aliased edges); the lettering is recoloured to `rgb`."""
    grey = Image.open(path).convert("L")
    alpha = grey.point(lambda v: 0 if v > 245 else round((255 - v) * 255 / 245))
    alpha = alpha.crop(alpha.getbbox())
    im = Image.new("RGBA", alpha.size, rgb + (0,))
    im.putalpha(alpha)
    return im


def b64(im):
    buf = io.BytesIO()
    im.save(buf, "PNG", optimize=True)
    return base64.b64encode(buf.getvalue()).decode()


light, dark = (lettering(SRC, rgb) for rgb in ((32, 33, 36), (255, 255, 255)))
w = round(light.width * H / light.height)
light, dark = (im.resize((w, H), Image.LANCZOS) for im in (light, dark))
OUT.write_text(
    "/* GENERATED by tools/brand/make_console_brand.py from static/brand/vyomi-text.png\n"
    " * (the official Vyomi text logo). Do not edit — re-run the script. */\n"
    f"export const WORDMARK_W = {w};\nexport const WORDMARK_H = {H};\n"
    f'export const WORDMARK_LIGHT = "data:image/png;base64,{b64(light)}";\n'
    f'export const WORDMARK_DARK = "data:image/png;base64,{b64(dark)}";\n')
print(f"wrote {OUT.relative_to(ROOT)} ({w}x{H}, {OUT.stat().st_size // 1024} KB)")
