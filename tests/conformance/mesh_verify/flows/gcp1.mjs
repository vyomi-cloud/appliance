import { open, check, BASE, SHOTS } from "../lib.mjs";
const { browser, page, errs } = await open();
await page.goto(`${BASE}/v4/gcp/#/iam-admin/iam`);
await page.getByRole("button", { name: "Grant access" }).first().click({ timeout: 30000 });
const panel = page.getByRole("dialog", { name: "Grant access" });
await panel.waitFor();
await panel.getByLabel("New principals").fill("gcpuser@example.com"); await panel.getByLabel("New principals").press("Enter");
await panel.getByRole("button", { name: "Select a role" }).click();
const popup = page.getByTestId("role-popup"); await popup.waitFor();
await popup.getByLabel("Search roles").fill("storage object viewer");
await popup.locator('[data-role-id="roles/storage.objectViewer"]').click();
await panel.getByRole("button", { name: "Add IAM condition" }).click();
const cond = page.getByRole("dialog", { name: "Add condition" }); await cond.waitFor();
await cond.getByLabel("Condition title").fill("allowed prefix only");
await cond.getByRole("tab", { name: "Condition editor" }).click();
await cond.getByLabel("CEL expression").fill('resource.name.startsWith("projects/_/buckets/vfy-gcp/objects/allowed/")');
await page.screenshot({ path: `${SHOTS}/gcp-g1-cond.png` });
await cond.getByRole("button", { name: "Save" }).click();
await panel.getByText("Condition: allowed prefix only").waitFor();
await page.screenshot({ path: `${SHOTS}/gcp-g1-grant.png` });
await panel.getByRole("button", { name: "Save", exact: true }).click();
await page.waitForTimeout(2000);
await page.screenshot({ path: `${SHOTS}/gcp-g1-saved.png` });
console.log(await page.locator("body").innerText().then(t=>/gcpuser@example.com/.test(t)));
console.log(errs);
await browser.close();
