import { open, check, BASE, SHOTS, done } from "../lib.mjs";
const { browser, page, errs } = await open();
const PN = process.env.PN, USER = process.env.USER_NAME;
const posts=[]; page.on("request",(r)=>{ if(r.method()==="POST"&&r.url().startsWith(BASE)) posts.push((r.postData()||"").slice(0,200)); });
await page.goto(`${BASE}/v4/aws/#/iam/create-policy`);
await page.getByText("Select a service").first().waitFor({ timeout: 30000 });
await page.getByRole("button", { name: /Choose a service/ }).first().click();
await page.getByPlaceholder("Search services").fill("S3");
await page.getByRole("option", { name: "S3", exact: true }).click();
await page.getByText("Specify actions from the service to be allowed.").waitFor();
await page.getByPlaceholder("Filter Actions").fill("ListAllMyBuckets");
await page.getByLabel("ListAllMyBuckets", { exact: true }).check();
await page.getByText("Resources", { exact: true }).first().click();
await page.getByRole("radio", { name: "All" }).first().check({ force: true }).catch(()=>{});
await page.getByRole("button", { name: "JSON", exact: true }).click();
const json = await page.getByLabel("Policy document").inputValue();
console.log(json);
check("AWS visual editor generates s3:ListAllMyBuckets Allow", /s3:ListAllMyBuckets/.test(json) && /Allow/.test(json));
await page.getByRole("button", { name: "Next", exact: true }).click();
await page.getByLabel("Policy name").fill(PN);
await page.screenshot({ path: `${SHOTS}/aws-a1-name.png` });
await page.getByRole("button", { name: "Create policy", exact: true }).click();
await page.waitForURL(new RegExp("iam/policies/"+PN), { timeout: 20000 }).catch(()=>{});
await page.waitForTimeout(1500);
await page.screenshot({ path: `${SHOTS}/aws-a1-created.png` });
check("create policy navigated to the real policy page", page.url().includes(PN), page.url());
// attach to user via the UI
await page.goto(`${BASE}/v4/aws/#/iam/users/${USER}`);
await page.getByRole("button", { name: "Add permissions" }).first().click();
const dlg = page.getByRole("dialog");
await dlg.getByLabel("Filter policies").fill(PN);
await page.waitForTimeout(500);
await dlg.getByRole("row", { name: new RegExp(PN) }).locator("input[type=checkbox],input[type=radio]").first().check({force:true});
await page.screenshot({ path: `${SHOTS}/aws-a1-attach.png` });
await dlg.getByRole("button", { name: /^(Add permissions|Attach policies|Attach)$/ }).last().click();
await page.waitForTimeout(1500);
await page.screenshot({ path: `${SHOTS}/aws-a1-attached.png` });
console.log(posts.join("\n"));
console.log(errs);
await browser.close();
