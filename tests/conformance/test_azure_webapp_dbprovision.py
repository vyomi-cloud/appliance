"""Create Web App > Database tab: the wizard's native ARM sequence (new SQL server + database, new
Cosmos DB account + listConnectionStrings) against the SAME ARM core, then the connection string
written to the web app's Microsoft.Web/sites/config/connectionstrings. Mirrors
consoles/src/azure/services/appservices/dbProvision.js + CreateWebApp.jsx.
Run: PYTHONPATH=. python3 tests/conformance/test_azure_webapp_dbprovision.py"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
from core.azure_arm_core import AzureArm, DEFAULT_SUBSCRIPTION as SUB  # noqa: E402

PASS = FAIL = 0


def check(name, ok, detail=""):
    global PASS, FAIL
    PASS, FAIL = PASS + (1 if ok else 0), FAIL + (0 if ok else 1)
    print(f"[{'PASS' if ok else 'FAIL'}] {name}{' - ' + str(detail)[:300] if detail and not ok else ''}")


RG = "dbapp-rg"
arm = AzureArm()
P = lambda ns, t, n: f"/subscriptions/{SUB}/resourceGroups/{RG}/providers/{ns}/{t}/{n}"
call = lambda m, path, av, body=None: arm.handle(m, path, {"api-version": av}, body)

check("rg", call("PUT", f"/subscriptions/{SUB}/resourceGroups/{RG}", "2021-04-01", {"location": "eastus"})["status"] == 200)

# ── SQL: new server + database ───────────────────────────────────────────────
srv = P("Microsoft.Sql", "servers", "appsqlsrv")
r = call("PUT", srv, "2023-08-01", {"location": "eastus", "properties": {"administratorLogin": "sqladmin", "administratorLoginPassword": "P@ssw0rd!x", "version": "12.0"}})
check("sql server created", r["status"] in (200, 201) and r["body"]["properties"]["administratorLogin"] == "sqladmin", r["body"])
r = call("PUT", srv + "/databases/appdb", "2023-08-01", {"location": "eastus", "sku": {"name": "Basic", "tier": "Basic", "capacity": 5}, "properties": {"status": "Online"}})
check("sql database created on that server", r["status"] in (200, 201) and r["body"]["name"].endswith("appdb"), r["body"])
g = call("GET", srv + "/databases/appdb", "2023-08-01")
check("sql database GET (shows in the SQL lens)", g["status"] == 200 and g["body"]["sku"]["name"] == "Basic", g["body"])
lst = call("GET", srv + "/databases", "2023-08-01")
check("sql database listed under the server", any(d["id"].lower().endswith("/servers/appsqlsrv/databases/appdb") for d in lst["body"]["value"]))

# ── Cosmos: new account + connection string ─────────────────────────────────
acct = P("Microsoft.DocumentDB", "databaseAccounts", "appcosmos")
r = call("PUT", acct, "2024-05-15", {"location": "eastus", "kind": "GlobalDocumentDB", "properties": {"databaseAccountOfferType": "Standard", "locations": [{"locationName": "eastus", "failoverPriority": 0}]}})
check("cosmos account created", r["status"] in (200, 201) and r["body"]["name"] == "appcosmos", r["body"])
cs = call("POST", acct + "/listConnectionStrings", "2024-05-15")["body"]["connectionStrings"]
primary = next(c["connectionString"] for c in cs if "Primary SQL" in c["description"])
check("cosmos primary connection string", primary.startswith("AccountEndpoint=https://appcosmos.documents.azure.com:443/;AccountKey="), primary)

# ── web app + connection strings ────────────────────────────────────────────
site = P("Microsoft.Web", "sites", "dbapp")
r = call("PUT", site, "2023-12-01", {"location": "eastus", "kind": "app,linux", "properties": {"autoGeneratedDomainNameLabelScope": "TenantReuse"}})
check("web app created (with unique hostname)", r["status"] in (200, 201) and "-01.azurewebsites.net" in r["body"]["properties"]["defaultHostName"], r["body"])
sql_cs = "Server=tcp:appsqlsrv.database.windows.net,1433;Initial Catalog=appdb;User ID=sqladmin;Password=P@ssw0rd!x;Encrypt=True;"
r = call("PUT", site + "/config/connectionstrings", "2023-12-01", {"properties": {
    "AZURE_SQL_CONNECTIONSTRING": {"value": sql_cs, "type": "SQLAzure"},
    "AZURE_COSMOS_CONNECTIONSTRING": {"value": primary, "type": "DocDb"}}})
check("connection strings PUT ok", r["status"] == 200, r["body"])
g = call("GET", site + "/config/connectionstrings", "2023-12-01")["body"]["properties"]
check("app has the SQL connection string (SQLAzure)", g.get("AZURE_SQL_CONNECTIONSTRING", {}).get("value") == sql_cs and g["AZURE_SQL_CONNECTIONSTRING"]["type"] == "SQLAzure", g)
check("app has the Cosmos connection string (DocDb)", g.get("AZURE_COSMOS_CONNECTIONSTRING", {}).get("value") == primary and g["AZURE_COSMOS_CONNECTIONSTRING"]["type"] == "DocDb", g)
l = call("POST", site + "/config/connectionstrings/list", "2023-12-01")
check("POST .../connectionstrings/list agrees", l["status"] == 200 and "AZURE_SQL_CONNECTIONSTRING" in l["body"]["properties"], l["body"])
print(f"\n{PASS} passed, {FAIL} failed")
sys.exit(1 if FAIL else 0)
