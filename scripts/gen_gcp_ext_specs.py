#!/usr/bin/env python3
"""Generate core/gcp_ext_specs.py: the compact method table core/gcp_wire_ext.py serves from.

Source: googleapiclient's bundled discovery documents (generation time only; output is committed, so the
simulator itself needs no Google client library).  One row per API method:
  (method id, HTTP verb, path regex source, list key, response kind, create-id query param)

  python3 scripts/gen_gcp_ext_specs.py
"""
import json
import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))

# api -> (discovery name, version, optional resource-name allow-list for the big Compute API)
APIS = [
    ("logging", "v2", None),
    ("iam", "v1", None),
    ("dns", "v1", None),
    ("networkmanagement", "v1", None),
    ("securitycenter", "v1", None),
    ("cloudfunctions", "v1", None),
    ("compute", "v1", {
        "firewallPolicies", "networkFirewallPolicies", "regionNetworkFirewallPolicies", "organizationSecurityPolicies",
        "securityPolicies", "regionSecurityPolicies", "networkAttachments", "serviceAttachments", "licenses", "sslPolicies",
        "regionSslPolicies", "httpHealthChecks", "httpsHealthChecks", "regionHealthChecks", "targetInstances", "targetPools",
        "targetVpnGateways", "externalVpnGateways", "vpnGateways", "vpnTunnels", "autoscalers", "regionAutoscalers",
        "regionInstantSnapshots", "instantSnapshots", "regionSnapshots", "regionDisks", "futureReservations",
        "regionNotificationEndpoints", "regionBackendBuckets", "backendBuckets", "targetTcpProxies", "targetSslProxies",
        "interconnectGroups", "crossSiteNetworks", "instanceGroupManagers", "regionInstanceGroupManagers", "targetHttpProxies",
        "targetHttpsProxies", "regionTargetHttpsProxies", "regionUrlMaps", "urlMaps", "backendServices", "regionBackendServices",
        "forwardingRules", "globalForwardingRules", "routers", "routes", "snapshots", "images", "disks", "addresses",
        "globalAddresses", "firewalls", "networks", "subnetworks", "instanceTemplates", "regionInstanceTemplates",
    }),
]


def methods(doc):
    out = []

    def walk(res, prefix):
        for mn, md in sorted((res.get("methods") or {}).items()):
            out.append((prefix + [mn], md))
        for rn, rd in sorted((res.get("resources") or {}).items()):
            walk(rd, prefix + [rn])
    walk(doc, [])
    return out


def regex_of(tpl):
    """'v2/projects/{projectsId}/sinks/{sinksId}:undelete' -> anchored regex source (verb kept literal)."""
    out, pos = "", 0
    for m in re.finditer(r"\{(\+?)([^}]+)\}", tpl):
        out += re.escape(tpl[pos:m.start()])
        out += "(?:[^/:?]+)" if not m.group(1) else "(?:.+?)"
        pos = m.end()
    out += re.escape(tpl[pos:])
    return "^/" + out + "$"


def main():
    from googleapiclient import discovery_cache
    ddir = os.path.join(os.path.dirname(discovery_cache.__file__), "documents")
    specs = {}
    for name, ver, allow in APIS:
        doc = json.load(open(os.path.join(ddir, "%s.%s.json" % (name, ver))))
        base = doc.get("servicePath", "")
        rows = []
        for ids, md in methods(doc):
            if allow is not None and not (set(ids) & allow):
                continue
            tpl = md.get("flatPath") or md.get("path", "")
            if base and not tpl.startswith(base.rstrip("/")):
                tpl = base + tpl
            resp = (md.get("response") or {}).get("$ref", "")
            lk = ""
            sch = (doc.get("schemas") or {}).get(resp) or {}
            for pk, pv in sorted((sch.get("properties") or {}).items()):
                if pv.get("type") == "array" and pk not in ("unreachable", "warnings", "permissions"):
                    lk = pk
                    break
            kind = "op" if resp in ("Operation", "GoogleLongrunningOperation") else ("empty" if resp in ("Empty", "GoogleProtobufEmpty") else ("res" if resp else "none"))
            idp = ""
            for pn, pd in sorted((md.get("parameters") or {}).items()):
                if pd.get("location") == "query" and pn.endswith("Id") and pn not in ("requestId", "projectId"):
                    idp = pn
                    break
            rows.append((md.get("id", ".".join([name] + ids)), md["httpMethod"], regex_of(tpl), lk, kind, idp, resp))
        specs["%s.%s" % (name, ver)] = rows
    path = os.path.join(ROOT, "core", "gcp_ext_specs.py")
    with open(path, "w") as f:
        f.write('"""GENERATED by scripts/gen_gcp_ext_specs.py from the Google discovery documents -- do not edit.\n\n'
                'Row: (method id, HTTP verb, path regex, list key, response kind, create-id query param, response schema)."""\n')
        f.write("SPECS = {\n")
        for k, rows in sorted(specs.items()):
            f.write("    %r: [\n" % k)
            for r in rows:
                f.write("        %r,\n" % (r,))
            f.write("    ],\n")
        f.write("}\n")
    print({k: len(v) for k, v in specs.items()})


if __name__ == "__main__":
    sys.path.insert(0, ROOT)
    main()
