#!/usr/bin/env python3
"""Generate wasm/service-inventory.json: the ONE catalogue of what Vyomi simulates, read by the portal (and anything else
that states a service count). Source of truth = the v4 console registries (consoles/src/<cloud>/services/registry.js, one entry
per service/product) plus the capability registry (core/capabilities/<cloud>/<service>.json, one entry per console feature).

    python3 scripts/gen_service_inventory.py           # rewrite wasm/service-inventory.json
    python3 scripts/gen_service_inventory.py --check   # exit 1 if the committed file is stale (CI / test)

Deterministic (no timestamps) so --check is exact. A service that is in a registry but missing here simply means this was not re-run:
tests/conformance/test_service_inventory.py fails until it is. See rule 13 in docs/architecture/v4.0/V4-BRANCH-ARCHITECTURE.md."""
import json, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "wasm", "service-inventory.json")
CLOUDS = ("aws", "gcp", "azure")
ENTRY = re.compile(r'^\s*\{\s*id:\s*"([^"]+)"(.*)$', re.M)
TITLE = re.compile(r'\btitle:\s*"([^"]*)"')
CAT = re.compile(r'\bcategory:\s*"([^"]*)"')


def features(cloud, sid):
    p = os.path.join(ROOT, "core", "capabilities", cloud, sid + ".json")
    if not os.path.exists(p):
        return None
    with open(p) as f:
        return sum(1 for k in json.load(f) if not k.startswith("$"))


def build():
    services = []
    for cloud in CLOUDS:
        with open(os.path.join(ROOT, "consoles", "src", cloud, "services", "registry.js")) as f:
            src = f.read()
        for sid, rest in ENTRY.findall(src):
            t, c = TITLE.search(rest), CAT.search(rest)
            services.append({"cloud": cloud, "id": sid, "title": t.group(1) if t else sid,
                             "category": c.group(1) if c else "", "v4": "load:" in rest, "features": features(cloud, sid)})
    live = [s for s in services if s["v4"]]
    by = {c: sum(1 for s in live if s["cloud"] == c) for c in CLOUDS}
    return {"$doc": "Generated by scripts/gen_service_inventory.py - do not edit. 'services' counts console registry entries with a v4 module; "
                    "'features' counts capability-registry entries (console features) for those services.",
            "totals": {"services": len(live), "by_cloud": by, "features": sum(s["features"] or 0 for s in live)},
            "services": services}


if __name__ == "__main__":
    text = json.dumps(build(), indent=1, ensure_ascii=False) + "\n"
    if "--check" in sys.argv:
        cur = open(OUT).read() if os.path.exists(OUT) else ""
        if cur != text:
            sys.exit("wasm/service-inventory.json is stale: run `python3 scripts/gen_service_inventory.py` and commit it")
        print("service inventory up to date")
    else:
        open(OUT, "w").write(text)
        t = json.loads(text)["totals"]
        print("wrote", OUT, t)
