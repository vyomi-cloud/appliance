#!/usr/bin/env python3
"""Tier / booster gating for the capability registry.

  --apply   write `tier` / `booster` from core/capabilities/_tiers.json into each
            core/capabilities/<cloud>/<svc>.json entry (text insert, no reformat; idempotent)
  (default) write wasm/tier-pills.json  (capability id -> pill, plus per-service rollup)
  --check   exit 1 if wasm/tier-pills.json is stale

Run: PYTHONPATH=. python3 scripts/gen_tier_pills.py [--apply|--check]
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from core.tier_policy import pill_for  # noqa: E402

REG = ROOT / "core" / "capabilities"
OUT = ROOT / "wasm" / "tier-pills.json"


def load_rules() -> dict:
    return json.loads((REG / "_tiers.json").read_text())["rules"]


def rule_for(fid: str, rules: dict):
    if fid in rules:
        return rules[fid]
    best = None
    for k, v in rules.items():
        if k.endswith("*") and fid.startswith(k[:-1]) and (best is None or len(k) > len(best[0])):
            best = (k, v)
    return best[1] if best else None


def registry_files():
    return [f for f in sorted(REG.glob("*/*.json")) if not f.name.startswith("_") and f.name != "schema.json"]


def apply() -> int:
    rules = load_rules()
    seen = set()
    for f in registry_files():
        text = f.read_text()
        data = json.loads(text)
        out = text
        for fid in [k for k in data if not k.startswith("$")]:
            r = rule_for(fid, rules)
            if not r:
                continue
            seen.add(fid)
            want = {k: r[k] for k in ("tier", "booster") if k in r}
            have = {k: data[fid][k] for k in ("tier", "booster") if k in data[fid]}
            if want == have:
                continue
            if have:
                print(f"ERROR {fid}: already carries {have}, expected {want}; clear it first")
                return 1
            pat = re.compile(r'^([ \t]*"%s"[ \t]*:[ \t]*\{[ \t]*\n)([ \t]+)' % re.escape(fid), re.M)
            # A few files repeat an id (last one wins when parsed): patch every occurrence.
            def ml(m):
                ind = m.group(2)
                return m.group(1) + "".join(f'{ind}"{k}": {json.dumps(v)},\n' for k, v in want.items()) + ind
            def sl(m):
                return m.group(1) + "".join(f'"{k}": {json.dumps(v)}, ' for k, v in want.items())
            out, n1 = pat.subn(ml, out)
            out, n2 = re.subn(r'^([ \t]*"%s"[ \t]*:[ \t]*\{)(?=")' % re.escape(fid), sl, out, flags=re.M)
            if n1 + n2 == 0:
                print(f"ERROR {fid}: cannot locate entry in {f}")
                return 1
        if out != text:
            json.loads(out)
            f.write_text(out)
    missing = sorted({k for k in rules if not k.endswith("*")} - seen)
    if missing:
        print("ERROR rules naming unknown capability ids:", ", ".join(missing))
        return 1
    return 0


def build() -> dict:
    caps, svc = {}, {}
    for f in registry_files():
        data = json.loads(f.read_text())
        pills = {}
        for fid, ent in data.items():
            if fid.startswith("$"):
                continue
            p = pill_for(ent)
            if p:
                caps[fid] = p
                pills[fid] = p
        if pills:
            svc[f"{f.parent.name}.{f.stem}"] = pills
    counts: dict = {}
    for p in caps.values():
        counts[p] = counts.get(p, 0) + 1
    return {"$doc": "Generated by scripts/gen_tier_pills.py - do not edit. capability id -> pill (Pro|Max|Booster); absent = no pill.",
            "counts": counts, "pills": dict(sorted(caps.items())), "services": dict(sorted(svc.items()))}


def main() -> int:
    if "--apply" in sys.argv:
        return apply()
    doc = json.dumps(build(), indent=1) + "\n"
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != doc:
            print("wasm/tier-pills.json is stale; run scripts/gen_tier_pills.py")
            return 1
        return 0
    OUT.write_text(doc)
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
