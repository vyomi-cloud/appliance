#!/usr/bin/env python3
"""Regenerate core/kubescape_catalog.py — the Kubescape control metadata (name, severity,
description, remediation, category, frameworks) for the frameworks Vyomi's Defender for Cloud
scans with, taken from the Kubescape CLI's own downloaded artifacts (kubescape/regolibrary,
Apache-2.0).

    docker run --rm -v "$PWD/ks-artifacts:/a" quay.io/kubescape/kubescape-cli:v4.0.16 download artifacts --output /a
    python3 scripts/gen_kubescape_catalog.py ks-artifacts
"""
import json
import pprint
import sys
from pathlib import Path

FRAMEWORKS = ["nsa", "mitre", "cis-v1.12.0"]
ROOT = Path(__file__).resolve().parents[1]


def severity(score) -> str:
    s = float(score or 0)
    return "Critical" if s >= 9 else "High" if s >= 7 else "Medium" if s >= 4 else "Low" if s >= 1 else "Unknown"


def main(art: str) -> None:
    catalog, fw_names = {}, {}
    for fw in FRAMEWORKS:
        doc = json.loads((Path(art) / f"{fw}.json").read_text())
        fw_names[fw] = doc["name"]
        for c in doc["controls"]:
            e = catalog.setdefault(c["controlID"], {
                "name": c["name"], "severity": severity(c.get("baseScore")), "baseScore": c.get("baseScore"),
                "description": (c.get("description") or "").strip(), "remediation": (c.get("remediation") or "").strip(),
                "category": ((c.get("category") or {}).get("name") or ""),
                "subCategory": (((c.get("category") or {}).get("subCategory") or {}).get("name") or ""),
                "scanningScope": ((c.get("scanningScope") or {}).get("matches") or []),
                "mitre": ((c.get("attributes") or {}).get("microsoftMitreColumns") or []),
                "frameworks": [],
            })
            e["frameworks"].append(doc["name"])
    out = ROOT / "core/kubescape_catalog.py"
    out.write_text(
        '"""GENERATED by scripts/gen_kubescape_catalog.py — do not edit by hand.\n\n'
        "Kubescape control metadata for the frameworks Vyomi's Defender for Cloud scans with\n"
        f"({', '.join(fw_names.values())}), from the Kubescape CLI v4.0.16 artifacts (kubescape/regolibrary,\n"
        'Apache-2.0, https://github.com/kubescape/regolibrary). Pure data — loads on host CPython and Pyodide.\n"""\n\n'
        f"FRAMEWORKS = {FRAMEWORKS!r}\n"
        f"FRAMEWORK_NAMES = {fw_names!r}\n\n"
        "CONTROLS = " + pprint.pformat(dict(sorted(catalog.items())), width=110, sort_dicts=True) + "\n")
    print(f"wrote {out} — {len(catalog)} controls")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "ks-artifacts")
