def parse_wg_dump(dump: str, now: Optional[float] = None, up_window_s: int = 200) -> List[dict]:
    """`wg show <if> dump` (tab separated; first line is the interface) -> peer rows with up/down by last handshake."""
    now = time.time() if now is None else now
    rows = []
    for line in dump.strip().splitlines()[1:]:
        f = line.split("\t")
        if len(f) < 8:
            continue
        hs = int(f[4] or 0)
        rows.append({"pubkey": f[0][:8] + "...", "allowed_ips": f[3], "last_handshake_s": (int(now - hs) if hs else None),
                     "rx_bytes": int(f[5]), "tx_bytes": int(f[6]), "up": bool(hs and now - hs < up_window_s)})
    return rows


def runner_urls(peers: Iterable[dict]) -> Dict[str, str]:
    """From a hub peer table -> {node_id: ollama base URL on the mesh} for runners that are up (what the gateway should use)."""
    return {p["id"]: f"http://{p['address']}:{OLLAMA_PORT}" for p in peers if p.get("role") == "runner" and p.get("up")}
