"""LLM MESH - portal-side session minting + address plan + peer-table helpers (design: docs/architecture/v4.0/BOOSTER-LLM-MESH.md).

The booster Codespace and up to 10 GitHub-Actions runners join one private WireGuard star (hub = the relay host, 100.96.0.1).
The portal decides WHO may join and WHERE (address); the nodes generate their own WireGuard keypairs and send only the PUBLIC key
to the hub at join time. So the portal-signed material is just a mesh-role session token per node - no WireGuard private key
and no preshared key ever exists outside the node that owns it. Tokens are short-lived (<= session_end) and re-minted for every
runner rotation (same node id => same address, new token, new key generated by the new process).

Token = the booster session token (core.booster_session wire format, same HMAC key) with role "mesh-node" and extra claims:
    node (id), mesh_addr, mesh_role ("booster"|"runner"), model (the runner id, for runners; informational)
The hub (wasm/relay/booster-mesh.mjs) authorises a join ONLY from those claims; a node can never pick its own address.

Address plan (CIDR 100.96.0.0/16, CGNAT space so it cannot clash with GitHub runner / Docker / Codespace nets):
    100.96.0.1      hub (relay host)
    100.96.0.2      the booster Codespace            (one)
    100.96.1.1-10   runners 1..10 (stable per runner id/slot; a rotated runner keeps its address)
"""
from __future__ import annotations

import base64
import hashlib
import hmac
import ipaddress
import json
import time
from typing import Any, Dict, Iterable, List, Optional, Tuple

from core import booster_session as bs

CIDR = "100.96.0.0/16"
HUB_ADDR = "100.96.0.1"
BOOSTER_ADDR = "100.96.0.2"
MAX_RUNNERS = 10
ROLE = "mesh-node"
RUNNER_PREFIX = "100.96.1."
WG_UDP_PORT = 51820          # hub listen port (loopback only; never published)
MTU = 1280
OLLAMA_PORT = 11434
RPC_PORT = 50052


class MeshError(ValueError):
    pass


def address_for(role: str, slot: int = 0) -> str:
    """Stable address: booster -> .0.2 ; runner slot 1..10 -> 100.96.1.<slot>."""
    if role == "booster":
        return BOOSTER_ADDR
    if role == "runner":
        if not 1 <= slot <= MAX_RUNNERS:
            raise MeshError(f"runner slot must be 1..{MAX_RUNNERS}")
        return f"{RUNNER_PREFIX}{slot}"
    raise MeshError(f"unknown mesh role {role!r}")


def plan(nodes: Iterable[dict]) -> Dict[str, dict]:
    """nodes: [{id, role}] (runners in a stable order). -> {id: {role, slot, address}}; rejects >1 booster / >10 runners / dup ids.
    A node may carry an explicit `slot` (a rotated runner reuses its slot); otherwise the first free slot is taken."""
    out: Dict[str, dict] = {}
    used: set = set()
    nodes = list(nodes)
    for n in nodes:
        if n.get("slot"):
            used.add(int(n["slot"]))
    boosters = 0
    for n in nodes:
        nid, role = str(n.get("id") or ""), n.get("role")
        if not nid or nid in out:
            raise MeshError(f"duplicate or empty node id {nid!r}")
        if role == "booster":
            boosters += 1
            if boosters > 1:
                raise MeshError("only one booster per mesh")
            out[nid] = {"role": role, "slot": 0, "address": BOOSTER_ADDR}
        elif role == "runner":
            slot = int(n.get("slot") or 0)
            if not slot:
                slot = next((s for s in range(1, MAX_RUNNERS + 1) if s not in used), 0)
                if not slot:
                    raise MeshError(f"at most {MAX_RUNNERS} runners per mesh")
                used.add(slot)
            out[nid] = {"role": role, "slot": slot, "address": address_for("runner", slot)}
        else:
            raise MeshError(f"unknown mesh role {role!r}")
    return out


def mint_node_token(account: str, session_id: str, node_id: str, role: str, address: str, session_end: float, *,
                    tier: str = "pro", key: Optional[str] = None, now: Optional[float] = None, model: str = "") -> str:
    now = time.time() if now is None else now
    payload: Dict[str, Any] = {"aud": bs.AUD, "sub": account, "tier": tier, "primary_cloud": "", "session_id": session_id,
                               "iat": int(now), "session_end": int(session_end), "role": ROLE, "node": node_id,
                               "mesh_addr": address, "mesh_role": role}
    if model:
        payload["model"] = model
    body = bs._b64(json.dumps(payload, separators=(",", ":"), sort_keys=True).encode())
    sig = hmac.new(bs._key(key), f"{bs.VERSION}.{body}".encode(), hashlib.sha256).digest()
    return f"{bs.VERSION}.{body}.{bs._b64(sig)}"


def mint_mesh_session(session_id: str, nodes: Iterable[dict], *, account: str = "acct", relay_url: str = "", session_end: float = 0,
                      tier: str = "pro", key: Optional[str] = None, now: Optional[float] = None, direct: str = "") -> Dict[str, dict]:
    """Per-node join configuration. Returns {node_id: config}; config.env is what the node's entrypoint needs
    (VYOMI_RELAY_URL, VYOMI_MESH_TOKEN, VYOMI_MESH_ADDR). NO key material: each node generates its keypair on itself and sends the
    public key to the hub through the token-authenticated join. `session_end` is epoch seconds (default: now + 5h50m, a runner job)."""
    now = time.time() if now is None else now
    session_end = session_end or now + 5 * 3600 + 50 * 60
    if not session_id:
        raise MeshError("session_id required")
    ap = plan(nodes)
    cfgs: Dict[str, dict] = {}
    for nid, a in ap.items():
        tok = mint_node_token(account, session_id, nid, a["role"], a["address"], session_end, tier=tier, key=key, now=now)
        cfgs[nid] = {
            "node": nid, "role": a["role"], "slot": a["slot"], "address": a["address"], "cidr": CIDR, "hub": HUB_ADDR, "mtu": MTU,
            "relay_url": relay_url, "direct": direct or None, "session_end": int(session_end),
            "services": {"ollama": f"http://{a['address']}:{OLLAMA_PORT}", "rpc": f"{a['address']}:{RPC_PORT}"} if a["role"] == "runner" else {},
            "env": {"VYOMI_RELAY_URL": relay_url, "VYOMI_MESH_TOKEN": tok, "VYOMI_MESH_ADDR": a["address"], "VYOMI_MESH_ROLE": a["role"]},
            "mask": [tok],     # values the entrypoint must ::add-mask:: before anything else (public-repo logs are world-readable)
        }
    return cfgs


def remint_for_rotation(session_id: str, node_id: str, role: str, slot: int, **kw) -> dict:
    """A runner rotates every ~5.5 h: the successor gets the SAME address (slot) + a fresh token; it generates a NEW keypair."""
    return mint_mesh_session(session_id, [{"id": node_id, "role": role, "slot": slot}], **kw)[node_id]


def verify_node_token(token: str, *, key: Optional[str] = None, now: Optional[float] = None) -> dict:
    c = bs.verify(token, key=key, now=now)
    if c.get("role") != ROLE:
        raise bs.SessionError("BoosterSessionWrongRole", "not a mesh-node token", 403)
    a = c.get("mesh_addr", "")
    try:
        ip = ipaddress.ip_address(a)
    except ValueError:
        raise bs.SessionError("MeshClaimsInvalid", "bad mesh address", 403)
    if ip not in ipaddress.ip_network(CIDR) or a == HUB_ADDR or not c.get("node"):
        raise bs.SessionError("MeshClaimsInvalid", "mesh address outside the plan", 403)
    return c


